import assert from "node:assert/strict";
import test from "node:test";
import { lintNoComments } from "@veristack/plugin-anti-slop";

test("rejects prose line and block comments in TypeScript", () => {
  const src = [
    "const total = 1;",
    "// increment total by one",
    "const next = total + 1;",
    "/* temporary hack until later */",
    "export const finalValue = next;",
  ].join("\n");
  const hits = lintNoComments("src/math.ts", src, "typescript");
  assert.equal(hits.length, 2);
  assert.equal(hits[0]?.line, 2);
  assert.equal(hits[1]?.line, 4);
});

test("allows directives, WARNING, SAFETY, license headers, vitest pragmas, and exported TSDoc", () => {
  const src = [
    "// @vitest-environment node",
    "// SPDX-License-Identifier: MIT",
    "/** Public contract doc. */",
    "export function parse(x: string): number {",
    "  // WARNING: floating point rounding affects invoice cents",
    "  // SAFETY: validated above before narrowing",
    "  // oxlint-disable-next-line no-bitwise",
    "  return Number(x) | 0;",
    "}",
  ].join("\n");
  const hits = lintNoComments("src/parse.ts", src, "typescript");
  assert.equal(hits.length, 0);
});

test("ignores comment-like tokens inside strings, URLs, regex literals, and Rust lifetimes", () => {
  const tsSrc = `export const endpoint = "https://example.com/a//b/*c*/";\nexport const re = /\\/\\/foo|\\/\\*bar\\*\\//g;`;
  assert.equal(lintNoComments("src/url.ts", tsSrc, "typescript").length, 0);

  const rsSrc = `pub fn first<'a>(items: &'a [i32]) -> &'a i32 { &items[0] }`;
  assert.equal(lintNoComments("src/lib.rs", rsSrc, "rust").length, 0);

  const pySrc = `url = "http://x.test/#anchor"\n# real prose comment\nx = 1`;
  const pyHits = lintNoComments("app.py", pySrc, "python");
  assert.equal(pyHits.length, 1);
  assert.equal(pyHits[0]?.line, 2);
});

test("skips auto-generated files only when both generated path and header banner match", () => {
  const src = [
    "// <auto-generated />",
    "// prose comment inside generated code",
    "export const v = 1;",
  ].join("\n");
  assert.equal(lintNoComments("src/gen.ts", src, "typescript").length, 0);

  const regularWithBanner = ["// <auto-generated />", "// normal prose comment", "export const v = 1;"].join("\n");
  assert.equal(lintNoComments("src/regular.ts", regularWithBanner, "typescript").length, 1);
  assert.equal(lintNoComments("src/generated/foo.ts", regularWithBanner, "typescript").length, 0);
  assert.equal(lintNoComments("src/generated/foo.ts", "// normal prose comment\nexport const v = 1;\n", "typescript").length, 1);
});
