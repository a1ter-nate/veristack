export function buildBlindAuditPrompt(packetPath: string, repoPath: string, modelLabel: string): string {
  return [
    `You are an independent verification-engineering auditor (${modelLabel}).`,
    `Perform a DOUBLE-BLIND ground-truth audit of the repository at ${repoPath}.`,
    `Read the harvested evidence packet first: ${packetPath}`,
    `You may also read any file inside ${repoPath} directly to verify citations, scripts, workflows, or tests.`,
    `Do NOT inspect any external analyzer or scoring tool — judge strictly from repository evidence.`,
    "",
    "Rules:",
    "1. Every boolean claim MUST be backed by concrete file:line citations from the repository.",
    "2. Distinguish PRODUCT workspaces from non-product directories (config, sample-demo, docs-site, benchmark-fuzz, codegen-macro, reexport-facade, e2e-harness).",
    "3. For each rung R0-R8, determine:",
    "   - applicable: is this rung applicable to this repo's real archetype? (R4/R7/R8 are normally not applicable to pure libraries; EXCEPT if a library explicitly ships DB adapters or browser/framework integrations with real DB/E2E test suites, mark R4/R7 applicable=true.)",
    "   - configuredTools: actual tools configured in manifests, configs, or tests (including custom linters like ast-grep, build orchestrators like build.ps1/cake.cs/Makefile, VM runners, CodSpeed, Stryker, Miri, etc.). Do NOT count product features (e.g. a browser plugin importing lighthouse) as verification tools.",
    "   - prBlockingCi.executed: does PR-blocking CI against the repo's ACTUAL default branch actually execute this rung?",
    "   - prBlockingCi.trustworthy: if executed=false, set trustworthy=true unless an actual evasion hazard exists. If executed=true, set trustworthy=false (with evasionHazard) ONLY if a step mutates $GITHUB_PATH, uses continue-on-error: true on a gate, swallows errors with '|| true', or poisons compiler/runner env vars.",
    "   - prBlockingCi.executionChain: exact chain (e.g. 'check.yml:check -> bun run lint -> oxlint + ast-grep') when executed=true.",
    "4. Rung definitions:",
    "   - R0: Static formatting, fast linting, anti-slop/custom static rules, pre-commit hooks, CODEOWNERS",
    "   - R1: Strict type checking, compiler warnings, dead-code checks, architectural/boundary lints",
    "   - R2: Pure/unit test suites, table-driven tests, property-based testing (PBT)",
    "   - R3: In-process boundary/host/component UI/contract tests, stateful model-based tests (MBT)",
    "   - R4: Real-engine integration tests (real DB, emulator, Testcontainers, pglite, broker) + migration verification",
    "   - R5: Mutation testing, formal verification/model checking, fuzzing, autonomous exploration, visual regression",
    "   - R6: Performance / load / Big-O benchmarks and budgets",
    "   - R7: End-to-end (Playwright/Cypress/Maestro/full-stack) golden-path suites",
    "   - R8: Live production telemetry (OpenTelemetry/Sentry/Prometheus), post-deploy smoke/canary/drift/rollback checks",
    "",
    "Return ONLY valid JSON (wrapped in a ```json code block) matching this exact schema:",
    JSON.stringify(
      {
        auditorModel: modelLabel,
        repo: "<repoName>",
        commitSha: "<sha>",
        defaultBranch: "<branch>",
        archetype: { value: "library|service|frontend|fullstack|os-infra-scripts", rationale: "<short>", citations: ["file:line"] },
        languages: { primary: ["typescript"], auxiliary: ["python"] },
        workspaces: [
          { path: "packages/core", role: "product", archetype: "library", hasOwnOrLinkedTests: true, testLocations: ["packages/core/test/"] },
        ],
        rungs: {
          R0: {
            applicable: true,
            configuredTools: [{ tool: "oxlint", citation: "package.json:17" }],
            prBlockingCi: { executed: true, trustworthy: true, executionChain: "check.yml:check -> bun run lint -> oxlint" },
            independentDepth: "solid",
          },
        },
      },
      null,
      2,
    ),
  ].join("\n");
}
